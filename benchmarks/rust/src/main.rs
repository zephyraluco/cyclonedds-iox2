use cyclonedds_sys as sys;
use std::ffi::{c_void, CString};
use std::io::{self, Write};
use std::ptr;
use std::time::{Duration, Instant};

// Only IDL descriptors come from C. DDS operations use the official Rust sys
// binding directly; this binary does not call the C benchmark endpoint.
extern "C" {
    static ShmBench_Small_desc: sys::dds_topic_descriptor_t;
    static ShmBench_Medium_desc: sys::dds_topic_descriptor_t;
    static ShmBench_Large_desc: sys::dds_topic_descriptor_t;
}
struct Options {
    server: bool,
    size: usize,
    count: usize,
    warmup: usize,
    window: usize,
    loan: bool,
    shm: bool,
    domain: u32,
    session: String,
}
fn options() -> Options {
    let a: Vec<String> = std::env::args().collect();
    assert_eq!(
        a.len(),
        10,
        "usage: PROGRAM client|server SIZE COUNT WARMUP WINDOW LOAN SHM DOMAIN SESSION"
    );
    assert!(a[1] == "client" || a[1] == "server");
    let n = |i: usize| a[i].parse::<usize>().expect("invalid numeric argument");
    let o = Options {
        server: a[1] == "server",
        size: n(2),
        count: n(3),
        warmup: n(4),
        window: n(5),
        loan: n(6) == 1,
        shm: n(7) == 1,
        domain: n(8) as u32,
        session: a[9].clone(),
    };
    assert!([64, 4096, 65536].contains(&o.size));
    assert!(
        o.count > 0
            && o.count <= 1_000_000
            && o.warmup <= 1_000_000
            && (1..=16).contains(&o.window)
            && n(6) <= 1
            && n(7) <= 1
            && n(8) <= 200
            && (!o.loan || o.shm)
            && o.session.len() < 80
    );
    o
}
fn check(rc: i32, operation: &str) -> i32 {
    assert!(rc >= 0, "{operation}: DDS return code {rc}");
    rc
}
struct Endpoint {
    participant: i32,
    writer: i32,
    reader: i32,
    waitset: i32,
    buffer: Vec<u64>,
    expected: Vec<u8>,
    size: usize,
    loan: bool,
    server: bool,
}
impl Endpoint {
    fn new(o: &Options) -> Self {
        // SAFETY: descriptors are generated by idlc. Handles are checked before
        // use and owned by Endpoint::drop; no guessed DDS struct layouts.
        unsafe {
            let desc = match o.size {
                64 => &raw const ShmBench_Small_desc,
                4096 => &raw const ShmBench_Medium_desc,
                _ => &raw const ShmBench_Large_desc,
            };
            assert_eq!((*desc).m_size as usize, o.size);
            let participant = check(
                sys::dds_create_participant(o.domain, ptr::null(), ptr::null()),
                "participant",
            );
            let mut topics = [0; 2];
            for (i, suffix) in ["request", "reply"].iter().enumerate() {
                let name = CString::new(format!("Bench_{}_{}", o.session, suffix)).unwrap();
                topics[i] = check(
                    sys::dds_create_topic(
                        participant,
                        desc,
                        name.as_ptr(),
                        ptr::null(),
                        ptr::null(),
                    ),
                    "topic",
                );
            }
            let qos = sys::dds_create_qos();
            assert!(!qos.is_null());
            sys::dds_qset_reliability(
                qos,
                sys::dds_reliability_kind_DDS_RELIABILITY_RELIABLE,
                5_000_000_000,
            );
            sys::dds_qset_durability(qos, sys::dds_durability_kind_DDS_DURABILITY_VOLATILE);
            sys::dds_qset_history(qos, sys::dds_history_kind_DDS_HISTORY_KEEP_LAST, 64);
            let writer = sys::dds_create_writer(
                participant,
                topics[usize::from(o.server)],
                qos,
                ptr::null(),
            );
            let reader = sys::dds_create_reader(
                participant,
                topics[usize::from(!o.server)],
                qos,
                ptr::null(),
            );
            sys::dds_delete_qos(qos);
            check(writer, "writer");
            check(reader, "reader");
            assert_eq!(
                sys::dds_is_shared_memory_available(writer),
                o.shm,
                "Rust writer SHM mismatch"
            );
            assert_eq!(
                sys::dds_is_shared_memory_available(reader),
                o.shm,
                "Rust reader SHM mismatch"
            );
            let waitset = check(sys::dds_create_waitset(participant), "waitset");
            let cond = check(
                sys::dds_create_readcondition(reader, sys::DDS_ANY_STATE),
                "read condition",
            );
            check(sys::dds_waitset_attach(waitset, cond, 1), "attach");
            let deadline = Instant::now() + Duration::from_secs(15);
            loop {
                let w = check(
                    sys::dds_get_matched_publications(reader, ptr::null_mut(), 0),
                    "matched writers",
                );
                let r = check(
                    sys::dds_get_matched_subscriptions(writer, ptr::null_mut(), 0),
                    "matched readers",
                );
                if w > 0 && r > 0 {
                    break;
                }
                assert!(Instant::now() < deadline, "Rust discovery timeout");
                std::thread::sleep(Duration::from_millis(5));
            }
            Self {
                participant,
                writer,
                reader,
                waitset,
                buffer: vec![0; o.size / 8],
                expected: vec![0xa5; o.size - 8],
                size: o.size,
                loan: o.loan,
                server: o.server,
            }
        }
    }
    fn send(&mut self, seq: u64) {
        // SAFETY: fixed IDL layout was checked: u64 plus an octet array. Vec<u64>
        // provides alignment; a successful DDS write consumes the writer loan.
        unsafe {
            let mut sample = self.buffer.as_mut_ptr().cast::<c_void>();
            if self.loan {
                check(
                    sys::dds_request_loan(self.writer, &mut sample),
                    "request loan",
                );
            }
            sample.cast::<u64>().write(seq);
            ptr::write_bytes(sample.cast::<u8>().add(8), 0xa5, self.size - 8);
            let rc = sys::dds_write(self.writer, sample);
            if rc < 0 && self.loan {
                sys::dds_return_loan(self.writer, &mut sample, 1);
            }
            check(rc, "write");
        }
    }
    fn receive(&self) -> u64 {
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            // SAFETY: inspect data only during the reader loan, then return it
            // before asserting validation or returning the sequence number.
            unsafe {
                let mut sample = ptr::null_mut();
                let mut info = sys::dds_sample_info_t::default();
                let n = check(
                    sys::dds_take(self.reader, &mut sample, &mut info, 1, 1),
                    "take",
                );
                if n > 0 {
                    let valid = info.valid_data;
                    let mut seq = 0;
                    let mut payload_ok = true;
                    if valid {
                        seq = sample.cast::<u64>().read();
                        payload_ok =
                            std::slice::from_raw_parts(sample.cast::<u8>().add(8), self.size - 8)
                                == self.expected.as_slice();
                    }
                    check(
                        sys::dds_return_loan(self.reader, &mut sample, n),
                        "return reader loan",
                    );
                    if valid {
                        assert!(payload_ok, "Rust corrupt payload");
                        return seq;
                    }
                }
                assert!(Instant::now() < deadline, "Rust receive timeout");
                let mut trigger = 0;
                check(
                    sys::dds_waitset_wait(self.waitset, &mut trigger, 1, 100_000_000),
                    "wait data",
                );
            }
        }
    }
}
impl Drop for Endpoint {
    fn drop(&mut self) {
        // SAFETY: Endpoint exclusively owns the participant and its children.
        unsafe {
            if self.server {
                let deadline = Instant::now() + Duration::from_secs(10);
                while sys::dds_get_matched_subscriptions(self.writer, ptr::null_mut(), 0) > 0 {
                    assert!(Instant::now() < deadline, "Rust peer close timeout");
                    std::thread::sleep(Duration::from_millis(5));
                }
            }
            check(sys::dds_delete(self.participant), "delete participant");
        }
    }
}
fn phase(ep: &mut Endpoint, first: usize, count: usize, window: usize, rtt: &mut [u64]) {
    for base in (0..count).step_by(window) {
        let batch = window.min(count - base);
        let mut starts = [Instant::now(); 16];
        for (j, t) in starts.iter_mut().enumerate().take(batch) {
            *t = Instant::now();
            ep.send((first + base + j) as u64);
        }
        for (j, t) in starts.iter().enumerate().take(batch) {
            let seq = ep.receive();
            let dt = t.elapsed().as_nanos() as u64;
            assert_eq!(seq, (first + base + j) as u64, "Rust sequence mismatch");
            if !rtt.is_empty() {
                rtt[base + j] = dt;
            }
        }
    }
}
fn main() {
    let o = options();
    let mut ep = Endpoint::new(&o);
    println!("DISCOVERED");
    io::stdout().flush().unwrap();
    let mut barrier = String::new();
    io::stdin().read_line(&mut barrier).unwrap();
    assert_eq!(barrier, "\n", "Rust missing peer discovery barrier");
    if o.server {
        for i in 0..o.count + o.warmup {
            let seq = ep.receive();
            assert_eq!(seq, i as u64, "Rust server sequence mismatch");
            ep.send(seq);
        }
        assert_eq!(ep.receive(), u64::MAX, "Rust completion missing");
        ep.send(u64::MAX);
    } else {
        let mut rtt = vec![0; o.count];
        phase(&mut ep, 0, o.warmup, o.window, &mut []);
        println!("READY");
        io::stdout().flush().unwrap();
        let mut line = String::new();
        io::stdin().read_line(&mut line).unwrap();
        assert_eq!(line, "\n");
        let t = Instant::now();
        phase(&mut ep, o.warmup, o.count, o.window, &mut rtt);
        let seconds = t.elapsed().as_secs_f64();
        ep.send(u64::MAX);
        assert_eq!(ep.receive(), u64::MAX, "Rust completion ack missing");
        rtt.sort_unstable();
        println!(
            "{}",
            serde_json::json!({"language":"rust","size_bytes":o.size,"samples":o.count,
            "warmup":o.warmup,"window":o.window,"loan":u8::from(o.loan),"shm":u8::from(o.shm),
            "elapsed_s":seconds,"p50_rtt_us":rtt[(o.count-1)/2] as f64/1000.0,
            "p99_rtt_us":rtt[(o.count*99+99)/100-1] as f64/1000.0,"samples_per_s":o.count as f64/seconds,
            "payload_mib_per_s":(o.count*o.size) as f64/seconds/1048576.0})
        );
    }
}
